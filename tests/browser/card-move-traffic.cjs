const assert=require('node:assert/strict'),path=require('node:path');
const pw=require(process.env.PLAYWRIGHT_PATH);
(async()=>{
 const browser=await pw.chromium.launch({headless:true,channel:'msedge'}),page=await browser.newPage();
 await page.setContent('<!doctype html><body></body>');
 await page.addScriptTag({path:path.join(__dirname,'.build/fixture.js')});
 await page.locator('sg-table sg-card').first().waitFor();
 const result=await page.evaluate(async()=>{
   const f=window.fixture,c=f.controller,base='game/6/tableDecks/pai/cards/';
   const target=f.table.playerDoms.find(player=>player.dataset.key==='p1').other1Area.cardsRef;
   f.resetMetrics();
   await c.moveOrderedCards([base+'c0',base+'c1'],target);
   const move=f.getMetrics();
   f.resetMetrics();
   const areaPath='game/6/p1/other1/cards',cards=f.read(areaPath);
   const keys=Object.keys(cards).sort((a,b)=>cards[a].order-cards[b].order);
   await c.moveOrderedCards([`${areaPath}/${keys[1]}`],target,keys[0]);
   const reorder=f.getMetrics();
   const selected=[f.table.paiArea.cards.c2,f.table.paiArea.cards.c3];
   c.selectedCards=selected;
   f.resetMetrics();
   await c.dropSeletedCards(target);
   const legacyBatch=f.getMetrics();
   f.resetMetrics();
   await c.moveOrderedCards(['game/6/p2/hand/cards/c0'],target);
   const countedMove=f.getMetrics();
   return {move,reorder,legacyBatch,countedMove,target:f.read(areaPath),source0:f.read(base+'c0'),source1:f.read(base+'c1'),source2:f.read(base+'c2'),source3:f.read(base+'c3'),p2HandCount:f.read('game/6/p2/areaCounts/hand'),p1AreaCount:f.read('game/6/p1/areaCounts/other1')};
 });
 assert.equal(Object.keys(result.target).length,5);assert.equal(result.source0,null);assert.equal(result.source1,null);assert.equal(result.source2,null);assert.equal(result.source3,null);assert.equal(result.p2HandCount,4);assert.equal(result.p1AreaCount,5);
 assert.ok(result.move.transactions.length>=1);
 assert.ok(result.move.transactions.every(item=>item.path.startsWith('game/6/operationLocks/')));
 assert.deepEqual(result.move.gets.map(item=>item.path).sort(),['game/6/p1/other1/cards', 'game/6/tableDecks/pai/cards/c0','game/6/tableDecks/pai/cards/c1'].sort());
 assert.equal(result.move.updates.length,1);assert.equal(result.move.updates[0].paths.some(path=>path==='game/6'),false);
 assert.ok(result.reorder.transactions.every(item=>item.path.startsWith('game/6/operationLocks/')));
 assert.ok(result.reorder.updates[0].paths.filter(path=>path.endsWith('/order')).length<=2);
 assert.deepEqual(result.legacyBatch.gets.map(item=>item.path).sort(),['game/6/p1/other1/cards','game/6/tableDecks/pai/cards/c2','game/6/tableDecks/pai/cards/c3'].sort());
 assert.equal(result.legacyBatch.updates.length,1);
 assert.deepEqual(result.countedMove.gets.map(item=>item.path).sort(),['game/6/p1/other1/cards','game/6/p2/hand/cards/c0','game/6/p2/areaCounts/hand'].sort());
 assert.equal(result.countedMove.updates.length,1);
 await browser.close();console.log('PASS: M01-M02 use narrow reads/writes with operation locks.');
})().catch(error=>{console.error(error);process.exit(1)});
